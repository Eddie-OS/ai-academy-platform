-- =============================================================================
-- V1_010__refine_selfcheck_item_columns.sql
--
-- 自检 CheckList 题库（cfg_selfcheck_item）的两处修正。1D 要把 14 条题目装进去，
-- 装之前先把列对齐到题库真正需要表达的东西，否则 14 行数据会带着错误的语义落库，
-- 阶段 2 的自检页面再改一次列、重灌一次数据。
--
-- 修正一：required BOOLEAN（是否必检）→ note_requirement VARCHAR（说明的必填性）
--
--   V1_001 按需求 13.9.3 的汇总表把这一列建成「是否必检」。但 13.9.3 是配置中心的
--   字段概览，规范性的定义在需求 9.4.1：清单项可配置的属性是「新增、停用、调整顺序、
--   **设置是否需填写说明**、设置分组」——没有「必检」。CK1／CK2 的完成度口径也只用到
--   两件事：勾没勾、说明必填时填没填。**全项目没有任何规则消费「必检」**。
--
--   而《课程自检CheckList初版》三的 14 条题目每条都带一个三档取值（必填／选填／无），
--   它决定界面上要不要给输入框、以及 CK2 的「勾选但未填说明视为未完成」是否生效。
--   一个布尔列装不下三档，硬装就会把「无需说明」和「选填说明」压成同一种，
--   B1、B3 这两条纯勾选题会长出一个永远没人填的输入框。
--
-- 修正二：补 guide_text（填写指引）
--
--   《课程自检CheckList初版》四把「填写指引」列为配置字段（≤300 字，显示为问题下方的
--   浅色提示）。初版为 14 条各写了指引文案，例如 C1 的「请写明岗位或角色，而不是部门名称」——
--   这些文案是这份清单的主要价值所在，不落库就只能留在文档里。
--
-- 为什么不改 V1_001：规则 DB-3 已合并的脚本禁止修改，修正一律新增脚本。
-- 直接 DROP 列是安全的：题库的初始数据由 R__ 脚本装载（本次一并新增），
-- 消费方（课程自检页面）在阶段 2，此刻表里没有任何行、也没有任何代码读它。
-- =============================================================================

ALTER TABLE cfg_selfcheck_item
    DROP COLUMN required,
    ADD COLUMN note_requirement VARCHAR(8) NOT NULL DEFAULT '选填',
    ADD COLUMN guide_text VARCHAR(300);

ALTER TABLE cfg_selfcheck_item
    ADD CONSTRAINT ck_selfcheck_note_requirement
        CHECK (note_requirement IN ('无', '选填', '必填'));

COMMENT ON COLUMN cfg_selfcheck_item.note_requirement IS
    '说明文本的必填性（需求 9.4.1「设置是否需填写说明」、9.4.2、规则 CK2）。'
    '无 = 纯勾选题，界面不给输入框；选填 = 给输入框但不影响完成度；必填 = 勾选但未填说明视为未完成';
COMMENT ON COLUMN cfg_selfcheck_item.guide_text IS
    '填写指引（《课程自检CheckList初版》四）。显示为问题下方的浅色提示文字，不占输入框';

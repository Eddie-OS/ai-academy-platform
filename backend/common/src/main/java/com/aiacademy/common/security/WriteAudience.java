package com.aiacademy.common.security;

/**
 * 写接口的开放范围（需求 6.2 权限矩阵）。{@link WriteApi} 的取值。
 *
 * <p><b>这个枚举不是账号类型</b>，因此可以出现在任何模块的 Controller 上而不违反 AR-7：
 * 它声明的是「这个接口对谁开放」，不是「当前登录的是谁」。把两者混为一谈，
 * 判权逻辑就会重新散回业务代码里。
 */
public enum WriteAudience {

    /**
     * 仅运营账号（需求 6.2 规则 PM1）。<b>绝大多数写接口都是这一档，也是默认值。</b>
     */
    OPERATOR_ONLY,

    /**
     * 用户账号也可写。<b>整个一期只有两个接口属于这一档</b>：案例点赞与案例评论（需求 6.2.5）。
     *
     * <p>新增第三个必须先改需求 6.2 的权限矩阵——ArchUnit 会拦下写在其他模块上的这一档声明。
     */
    USER_ALLOWED,

    /**
     * 未登录也可访问的写接口。<b>只有登录与登出</b>：请求到达时还没有账号类型可判，
     * 而用户账号也必须能够登录。
     */
    ANONYMOUS
}

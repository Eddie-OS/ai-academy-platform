package com.aiacademy.platform.statemachine.domain;

import java.util.List;
import java.util.Set;

/**
 * 一个状态机的定义。<b>主键是（对象类型 + 状态字段名）</b>，不是对象类型本身
 * （《开发实施文档》5.1.3）。
 *
 * <p>需求文档里一个对象可以有多个独立的状态字段：需求有 3 组状态字段 + 交付标记，
 * 课程有主状态 + 4 组子状态。建模成「一个对象一个状态机」就无处安放它们。
 * 这个口径也与需求 5.11 状态流转日志的「状态字段名」列一致。
 *
 * <p>一期共 <b>15 个业务状态机</b>（权威清单在需求 5.13），加上任务状态机共 <b>16 张转换表</b>——
 * 任务是支撑对象，需求 5.13 明确列在 15 之外，但引擎照样要装载它。
 *
 * <p><b>讲师培养状态不是状态机</b>（C10）。它有多个取值、会随时间推进、看起来完全像状态机，
 * 但业务上允许自由跳转。做成状态机会在「改错了想改回去」时拦住运营，而这个限制从未被要求过。
 * 判断依据很简单：需求第 5 章里有它的转换表吗？没有。
 */
public interface StateMachineDef {

    /** 状态机名，与需求 5.13 清单逐字一致。参数化测试用它与需求文档对账。 */
    String machineName();

    /** 对象类型码，如 {@code COURSE}。与状态流转日志的 object_type 列一致。 */
    String objectType();

    /** 状态字段名（中文），如「课程主状态」。与状态流转日志的 state_field 列一致。 */
    String stateField();

    /** 全部转换，顺序与需求表格一致，便于逐行比对。 */
    List<Transition> transitions();

    /**
     * 终态集合：<b>对象生命周期结束</b>的状态。
     *
     * <p>用于需求 13.1.2 的自动关闭规则「业务对象转入终态（已归档 / 已关闭 / 课程归档 / 案例归档）时，
     * 其下所有未完成任务自动置已关闭」，以及三色灯的退出预警判定。
     *
     * <p><b>必须逐个状态机显式声明，不能用「没有出向转换」推导。</b>推导会把子状态机的死胡同
     * 也算成终态——课程「试讲状态=待发布」「课程发布状态=已发布」「课程自检状态=（空）」
     * 都没有出向转换，但课程的生命周期由主状态决定，这三个都不是终态。
     * 按推导结果去关闭任务，课程一进入「发布」就会把它下面的任务全关掉。
     *
     * <p><b>也不要与「退出预警范围」混为一谈。</b>培训计划「已完成」退出预警范围但有一条
     * 「退回执行中」，案例「已上架」也有「下架修改」——它们都不是终态。
     * 退出预警范围标在 {@link Transition#exitsWarningScope()} 上。
     */
    Set<String> terminalStates();
}
